#!/usr/bin/env python3
"""Turn an 8-pixel-wide PSF1/PSF2 console font into src/font.h (ASCII 0..127)."""
import gzip
import struct
import sys

src, dst = sys.argv[1], sys.argv[2]
data = gzip.open(src).read() if src.endswith(".gz") else open(src, "rb").read()

if data[:2] == b"\x36\x04":
    height = data[3]
    glyphs, off, width = data[4:], 0, 8
elif data[:4] == b"\x72\xb5\x4a\x86":
    _, _, hdr, _, _, gbytes, height, width = struct.unpack("<8I", data[:32])
    glyphs, off = data[hdr:], 0
    if width != 8 or gbytes != height:
        sys.exit("need an 8-pixel-wide font")
else:
    sys.exit("not a PSF font")

with open(dst, "w") as f:
    f.write("/* generated by tools/mkfont.py from %s */\n" % src.split("/")[-1])
    f.write("#define FONT_W 8\n#define FONT_H %d\n" % height)
    f.write("static const unsigned char font_bits[128][%d] = {\n" % height)
    for c in range(128):
        row = glyphs[off + c * height: off + (c + 1) * height]
        f.write("\t{" + ",".join("0x%02x" % b for b in row) + "},\n")
    f.write("};\n")
